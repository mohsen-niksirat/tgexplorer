// worker-code.js is generated from worker.js by this script.
// worker.js is read verbatim, and every character that would be
// interpreted by the template literal is escaped (backslash, backtick,
// dollar-brace). Everything else is kept byte-for-byte identical, so a
// user who copies the setup-screen code gets a working worker.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(ROOT, 'worker.js'), 'utf8');

const escaped = src
  .replace(/\\/g, '\\\\')
  .replace(/`/g, '\\`')
  .replace(/\$\{/g, '\\${');

const eol = src.includes('\r\n') ? '\r\n' : '\n';
const out =
  '// ============================================================' + eol +
  '// worker-code.js — the Cloudflare Worker source shown in the' + eol +
  '// setup screen. GENERATED by scripts/build-worker-code.js — do' + eol +
  '// not edit by hand; edit worker.js and re-run the script.' + eol +
  '// ============================================================' + eol +
  'export const WORKER_CODE=`' + escaped + '`;' + eol;

fs.writeFileSync(path.join(ROOT, 'js', 'worker-code.js'), out, 'utf8');
console.log('written js/worker-code.js (' + out.length + ' bytes)');

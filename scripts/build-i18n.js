// Generate js/i18n.js from the translation files in i18n/.
//
//   node scripts/build-i18n.js
//
// The JSON files are the source of truth. This script turns them back into
// the module the app imports.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const I18N_DIR = path.join(ROOT, 'i18n');
const LANGS = ['en', 'fa', 'ar', 'zh', 'ru', 'es', 'fr'];

const esc = s => String(s == null ? '' : s)
  .replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n').replace(/\r/g, '');

const data = {};
for (const lang of LANGS) {
  const file = path.join(I18N_DIR, lang + '.json');
  if (!fs.existsSync(file)) { console.error('missing: i18n/' + lang + '.json'); process.exit(1); }
  data[lang] = JSON.parse(fs.readFileSync(file, 'utf8'));
}

// The keys, in the order English has them.
const mainKeys = Object.keys(data.en.main);
const uiKeys = Object.keys(data.en.ui);

const obj = (lang, group, keys) => {
  const parts = keys
    .filter(k => data[lang][group] && data[lang][group][k] !== undefined)
    .map(k => k + ":" + JSON.stringify(data[lang][group][k]));
  return '{' + parts.join(',') + '}';
};

const header = `// ============================================================
// i18n.js — all UI strings for the 7 supported languages.
// GENERATED by scripts/build-i18n.js from the files in i18n/ —
// do not edit this file, edit i18n/<lang>.json and run the script.
// ============================================================
import { state } from './state.js';

export const I18N = {
`;

const middle = LANGS.map(l => '  ' + l + ': ' + obj(l, 'main', mainKeys) + ',').join('\n');

const ui = `
export const I18N_UI = {
` + LANGS.map(l => '  ' + l + ': ' + obj(l, 'ui', uiKeys) + ',').join('\n') + `
};

export const RTL_LANGS = ['fa', 'ar'];

export function applyLang(lang) {
  const t = I18N[lang] || I18N.en;
  document.documentElement.lang = lang;
  document.documentElement.dir = RTL_LANGS.includes(lang) ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.dataset.i18n;
    if (t[k]) el.textContent = t[k];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const k = el.dataset.i18nPlaceholder;
    if (t[k]) el.placeholder = t[k];
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    const k = el.dataset.i18nAriaLabel;
    if (t[k]) el.setAttribute('aria-label', t[k]);
  });
}

export function t(key) {
  const L = I18N[state.lang] || I18N.en;
  let s;
  if (key in L) s = L[key];
  else if (I18N_UI && key in (I18N_UI[state.lang] || {})) s = I18N_UI[state.lang][key];
  else if (I18N.en[key] != null) s = I18N.en[key];
  else if (I18N_UI && I18N_UI.en && key in I18N_UI.en) s = I18N_UI.en[key];
  else return key;
  for (let i = 0; i < arguments.length - 1; i++) {
    s = String(s).replace(new RegExp('\\\\{' + i + '\\\\}', 'g'), arguments[i + 1]);
  }
  return s;
}
`;

const out = header + middle + '\n};\n' + ui;
fs.writeFileSync(path.join(ROOT, 'js', 'i18n.js'), out, 'utf8');
console.log('wrote js/i18n.js (' + out.length + ' bytes)');
console.log('  main: ' + mainKeys.length + ' keys, ui: ' + uiKeys.length + ' keys');
